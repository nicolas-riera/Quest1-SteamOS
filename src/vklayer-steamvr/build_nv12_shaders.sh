#!/bin/sh
# Compile nv12_copy.vert/.frag and nv12_inset.frag into quest1_nv12_spv.h (SPIR-V words for quest1_modifier.c). Needs glslangValidator
# (WSL Debian: apt install glslang-tools). The header is committed: the layer builds without it.
set -e
cd "$(dirname "$0")"
glslangValidator -V --vn nv12_copy_vert -o vert.h nv12_copy.vert >/dev/null
glslangValidator -V --vn nv12_copy_frag -o frag.h nv12_copy.frag >/dev/null
glslangValidator -V --vn nv12_inset_frag -o inset.h nv12_inset.frag >/dev/null
{
	echo "// Generated by build_nv12_shaders.sh from nv12_copy.vert, nv12_copy.frag and nv12_inset.frag: do not edit."
	cat vert.h frag.h inset.h
} > quest1_nv12_spv.h
rm -f vert.h frag.h inset.h
