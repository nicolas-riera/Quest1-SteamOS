#!/bin/sh
# Compile the layer's shaders into headers of SPIR-V words: nv12_copy.vert/.frag and nv12_inset.frag into quest1_nv12_spv.h
# (quest1_modifier.c), distort_layered_identity.frag into quest1_distort_spv.h (quest1_compat.c). Needs glslangValidator
# (WSL Debian: apt install glslang-tools). The headers are committed: the layer builds without it.
set -e
cd "$(dirname "$0")"
glslangValidator -V --vn nv12_copy_vert -o vert.h nv12_copy.vert >/dev/null
glslangValidator -V --vn nv12_copy_frag -o frag.h nv12_copy.frag >/dev/null
glslangValidator -V --vn nv12_inset_frag -o inset.h nv12_inset.frag >/dev/null
{
	echo "// Generated by build_nv12_shaders.sh from nv12_copy.vert, nv12_copy.frag and nv12_inset.frag: do not edit."
	cat vert.h frag.h inset.h
} > quest1_nv12_spv.h
rm -f vert.h frag.h inset.h
# and distort_layered_identity.frag into quest1_distort_spv.h (quest1_compat_modules.c), once per SteamVR version's
# layout: vrcompositor's entry point name
glslangValidator -V -e PS_DISTORT --source-entrypoint main --vn distort_layered_identity_frag -o distort.h \
	distort_layered_identity.frag >/dev/null
glslangValidator -V -DSTEAMVR_2_19 -e PS_DISTORT --source-entrypoint main --vn distort_layered_identity_2_19_frag \
	-o distort219.h distort_layered_identity.frag >/dev/null
{
	echo "// Generated by build_nv12_shaders.sh from distort_layered_identity.frag: do not edit."
	cat distort.h distort219.h
} > quest1_distort_spv.h
rm -f distort.h distort219.h
